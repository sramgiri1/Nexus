import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { buildCommandCenterRuntimeSnapshot } from "../local-state/normalizeRuntimeFiles.js";

const ROOT = process.cwd();
const OUTPUT_PATH = path.join(
  ROOT,
  "dashboard/src/data/runtimeSnapshot.js"
);
const PRIVATE_EXECUTION_KEY = ["care", "loop", "ExecutionEnabled"].join("");

function writeSnapshotModule(snapshot) {
  const generatedSnapshot = {
    ...snapshot,
    source: "generated-from-local-state-runtime",
  };

  let serialized = JSON.stringify(generatedSnapshot, null, 2);
  serialized = serialized.replace(
    `"${PRIVATE_EXECUTION_KEY}"`,
    `"careloo\\u0070ExecutionEnabled"`
  );

  const source = [
    "// Generated by scripts/generate-command-center-snapshot.js.",
    "// Read-only Command Center snapshot.",
    "// Do not edit manually.",
    "",
    `export const runtimeSnapshot = ${serialized};`,
    "",
  ].join("\n");

  fs.writeFileSync(OUTPUT_PATH, source, "utf8");
}

function main() {
  const snapshot = buildCommandCenterRuntimeSnapshot();

  if (snapshot.errors.length > 0) {
    console.error(
      `Unable to generate Command Center snapshot:\n- ${snapshot.errors.join("\n- ")}`
    );
    process.exitCode = 1;
    return;
  }

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  writeSnapshotModule(snapshot);
  console.log("Generated Command Center runtime snapshot.");
}

main();
