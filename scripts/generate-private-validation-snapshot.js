import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import {
  buildPrivateValidationSnapshot,
  validatePrivateValidationSnapshot,
} from "../private-mode/privateValidationSnapshot.js";

const ROOT = process.cwd();
const REPORT_PATH = path.join(ROOT, "reports/private-validation-snapshot.json");
const MODULE_PATH = path.join(
  ROOT,
  "dashboard/src/data/privateValidationSnapshot.js"
);

function writeFile(targetPath, content) {
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, content, "utf8");
}

function buildModuleSource(snapshot) {
  return [
    "// Generated by scripts/generate-private-validation-snapshot.js.",
    "// Local-private read-only validation snapshot.",
    "// Do not edit manually.",
    "// Do not publish as public demo data.",
    "",
    `export const privateValidationSnapshot = ${JSON.stringify(snapshot, null, 2)};`,
    "",
  ].join("\n");
}

function main() {
  const snapshot = buildPrivateValidationSnapshot();
  const validation = validatePrivateValidationSnapshot(snapshot);

  if (!validation.valid || snapshot.errors.length) {
    const issues = [...validation.errors, ...snapshot.errors];
    for (const issue of issues) {
      console.error(issue);
    }
    process.exitCode = 1;
    return;
  }

  writeFile(REPORT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`);
  writeFile(MODULE_PATH, buildModuleSource(snapshot));

  console.log("NEXUS Private Validation Snapshot");
  console.log("================================");
  console.log(`Mode: ${snapshot.mode}`);
  console.log(`Project: ${snapshot.project.label}`);
  console.log(`Overall: ${snapshot.status.overall}`);
  console.log(
    `Backend tests: ${snapshot.status.latestBackendValidation.testsPassed}/${snapshot.status.latestBackendValidation.totalTests} ${snapshot.status.latestBackendValidation.status}`
  );
  console.log(`Output: ${path.relative(ROOT, REPORT_PATH)}`);
  console.log(`Dashboard module: ${path.relative(ROOT, MODULE_PATH)}`);
}

main();
