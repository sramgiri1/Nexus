import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { getNexusMode, requireLocalPrivateMode } from "../private-mode/privateMode.js";
import {
  ACTION_TYPES,
  buildAction,
  readRecentActions,
} from "../action-bridge/index.js";
import { routeActionRequest } from "../action-bridge/actionRouter.js";

const ROOT = process.cwd();
const REPORT_JSON = path.join(ROOT, "reports/action-bridge-snapshot.json");
const DASHBOARD_MODULE = path.join(ROOT, "dashboard/src/data/actionBridgeSnapshot.js");

function writeFile(targetPath, content) {
  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, content, "utf8");
}

function buildDashboardModule(snapshot) {
  return [
    "// Generated by scripts/action-bridge-demo.js.",
    "// Local-private read-only action bridge snapshot.",
    "// Do not edit manually.",
    "// Do not publish as public demo data.",
    "",
    `export const actionBridgeSnapshot = ${JSON.stringify(snapshot, null, 2)};`,
    "",
  ].join("\n");
}

function buildSnapshot(action, routingResult, recentActions) {
  return {
    snapshotVersion: "1.0",
    mode: "local-private",
    source: "action-bridge-demo",
    readOnly: true,
    generatedAt: new Date(Date.now()).toISOString(),
    bridgeReadiness: {
      status: "READY",
      schemaValidated: true,
      governanceApplied: true,
      trafficPlane: true,
      stateMachine: true,
      localWriteBoundary: true,
    },
    lastDemoAction: {
      actionId: action.actionId,
      actionType: action.actionType,
      status: routingResult.routing?.status || "unknown",
      mode: action.mode,
      approvalRequired: routingResult.routing?.approvalRequired || false,
      commandExecuted: false,
      mutationApplied: false,
      providerCalled: false,
      networkCalled: false,
    },
    recentActions: (recentActions.records || []).map((record) => ({
      actionId: record.actionId,
      actionType: record.actionType,
      status: record.status,
      mode: record.mode,
      createdAt: record.createdAt,
    })),
    governance: {
      mutationEnabledFromUi: false,
      browserFilesystemWriteAllowed: false,
      directCommandExecutionAllowed: false,
      providerCallsAllowed: false,
      networkCallsAllowed: false,
      dbAccessAllowed: false,
    },
    cliCommand: "npm run action:bridge-demo",
    warnings: routingResult.warnings || [],
    errors: routingResult.errors || [],
  };
}

function main() {
  const mode = getNexusMode(process.env);
  const modeResult = requireLocalPrivateMode(mode);

  if (!modeResult.ok) {
    console.error("action:bridge-demo requires NEXUS_MODE=local-private");
    process.exitCode = 1;
    return;
  }

  const action = buildAction({
    actionType: ACTION_TYPES.PRIVATE_BACKEND_VALIDATION_REQUEST,
    requestedBy: "system",
    mode,
    projectId: "private-project-01",
    privateProject: true,
    target: {
      capabilityId: "verification.code_quality_gate",
      targetAgent: "auditor",
      riskLevel: "medium",
      dataClassification: "confidential",
    },
  });

  const routingResult = routeActionRequest(action, { env: process.env });

  if (!routingResult.ok) {
    console.error("Action bridge routing failed:");
    for (const error of routingResult.errors) {
      console.error(` - ${error}`);
    }
    process.exitCode = 1;
    return;
  }

  const recentActions = readRecentActions(5);
  const snapshot = buildSnapshot(action, routingResult, recentActions);

  writeFile(REPORT_JSON, `${JSON.stringify(snapshot, null, 2)}\n`);
  writeFile(DASHBOARD_MODULE, buildDashboardModule(snapshot));

  console.log("NEXUS Action Bridge Demo");
  console.log("========================");
  console.log(`Mode: ${mode}`);
  console.log(`Action type: ${action.actionType}`);
  console.log(`Action ID: ${action.actionId}`);
  console.log(`Routing status: ${routingResult.routing.status}`);
  console.log(`Approval required: ${routingResult.routing.approvalRequired}`);
  console.log(`Command executed: false`);
  console.log(`Provider called: false`);
  console.log(`Output: reports/action-bridge-snapshot.json`);
  console.log(`Dashboard module: dashboard/src/data/actionBridgeSnapshot.js`);

  if (routingResult.warnings.length) {
    console.log(`Warnings: ${routingResult.warnings.length}`);
  }
}

main();
